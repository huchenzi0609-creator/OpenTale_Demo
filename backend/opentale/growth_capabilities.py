"""Typed, versioned handles shared by projection validation and host execution.

This module knows only the delivered frame. It never queries a store, infers an
object from an ID prefix, or turns a method's private dependencies into access.
Old saved frames without a capability table use the same finite projections.
"""

from __future__ import annotations

from dataclasses import dataclass

KINDS = frozenset({"node", "method", "trial", "response", "visit", "passage", "link", "view"})
PAGE_KINDS = KINDS
TABLE_FIELD = "capabilities"


class CapabilityError(ValueError):
    """A finite diagnostic; rejected IDs and user text stay outside the error."""

    def __init__(self, issue: str):
        self.issue = issue
        super().__init__(issue)


@dataclass(frozen=True, slots=True)
class Capability:
    kind: str
    object_id: str
    version: str | None = None

    def as_dict(self) -> dict:
        return {"kind": self.kind, "object_id": self.object_id, "version": self.version}


def _kind(value: object) -> str | None:
    return "link" if value == "edge" else value if type(value) is str and value in KINDS else None


def _rows(frame: dict, name: str) -> list[dict]:
    rows = frame.get(name, [])
    if not isinstance(rows, list) or any(not isinstance(row, dict) for row in rows):
        raise CapabilityError("CAPABILITY_TABLE_INVALID")
    return rows


def collect_capabilities(frame: dict) -> tuple[Capability, ...]:
    """Collect public handles, preserving exact immutable versions and ambiguity.

    A present explicit table is authoritative. It is generated by the host after
    applying scope visibility, and may include visible dependencies not repeated
    in prose previews. The fallback exists for old frozen request snapshots.
    """
    found: set[Capability] = set()

    def add(kind: object, row: object, *, required: bool = False) -> None:
        if not isinstance(row, dict):
            if required:
                raise CapabilityError("CAPABILITY_TABLE_INVALID")
            return
        normalized = _kind(kind)
        key = row.get("object_id", row.get("id"))
        version = row.get("version")
        if (normalized is None or type(key) is not str or not key
                or version is not None and (type(version) is not str or not version)):
            if required:
                raise CapabilityError("CAPABILITY_TABLE_INVALID")
            return
        found.add(Capability(normalized, key, version))

    if TABLE_FIELD in frame:
        for row in _rows(frame, TABLE_FIELD):
            if not set(row) <= {"kind", "object_id", "id", "version"}:
                raise CapabilityError("CAPABILITY_TABLE_INVALID")
            add(row.get("kind"), row, required=True)
    else:
        for name, kind in (("nodes", "node"), ("sources", "node"), ("methods", "method"),
                           ("trials", "trial"), ("responses", "response"),
                           ("feedback_catalog", "response"), ("visits", "visit"),
                           ("reading_history", "passage"), ("links", "link"), ("views", "view")):
            for row in _rows(frame, name):
                add(kind, row)
                _structure(row, kind, add)
        for name, kind in (("method", "method"), ("evaluation_method", "method"),
                           ("pending_trial", "trial"), ("view", "view")):
            row = frame.get(name)
            add(kind, row)
            if isinstance(row, dict):
                _structure(row, kind, add)
        cache = frame.get("method_cache", [])
        if isinstance(cache, dict):
            cached = [*_rows(cache, "methods"), *_rows(cache, "refs")]
        elif isinstance(cache, list) and all(isinstance(row, dict) for row in cache):
            cached = cache
        else:
            raise CapabilityError("CAPABILITY_TABLE_INVALID")
        for method in cached:
            add("method", method)
        _execution(frame.get("method_execution"), add)
        for page in _rows(frame, "pages"):
            kind = _kind(page.get("kind"))
            if kind:
                add(kind, page)
                _structure(page, kind, add)
                items = page.get("items", [])
                if not isinstance(items, list) or any(not isinstance(item, dict) for item in items):
                    raise CapabilityError("CAPABILITY_TABLE_INVALID")
                for row in items:
                    add(kind, row)
                    _structure(row, kind, add)
                for field in ("object", "structure"):
                    if isinstance(page.get(field), dict):
                        add(kind, page[field])
                        _structure(page[field], kind, add)
            add("method", page.get("method"))
        for name in ("method_evidence", "method_dependencies"):
            for row in _rows(frame, name):
                add(row.get("kind"), row)
        work = frame.get("method_work") or {}
        if not isinstance(work, dict):
            raise CapabilityError("CAPABILITY_TABLE_INVALID")
        for name in ("adopted_ref", "applied_ref", "active_ref"):
            ref = work.get(name)
            if isinstance(ref, dict):
                add(ref.get("kind"), ref)
        for name in ("candidate_refs", "recent_result_refs", "recent_feedback_refs"):
            for ref in _rows(work, name):
                add(ref.get("kind"), ref)

    # An unversioned endpoint preview does not create ambiguity when a precise
    # version of the same typed handle has also actually been delivered.
    precise = {(cap.kind, cap.object_id) for cap in found if cap.version is not None}
    found = {cap for cap in found if cap.version is not None or (cap.kind, cap.object_id) not in precise}
    return tuple(sorted(found, key=lambda cap: (cap.kind, cap.object_id, cap.version or "")))


def _structure(row: dict, kind: str, add) -> None:
    if kind == "link":
        for field in ("source_id", "target_id"):
            if type(row.get(field)) is str:
                add("node", {"id": row[field], "version": row.get(field.removesuffix("_id") + "_version")})
    elif kind == "view":
        members = row.get("members", [])
        if not isinstance(members, list):
            raise CapabilityError("CAPABILITY_TABLE_INVALID")
        for member in members:
            if isinstance(member, dict):
                add(member.get("kind", "node"), member)
        for ref in _rows(row, "input_refs"):
            add(ref.get("kind"), ref)
        _execution(row.get("execution"), add)


def _execution(execution: object, add) -> None:
    """Only an executed, scope-checked plan contributes public exact handles."""
    if not isinstance(execution, dict):
        return
    root = execution.get("root_ref")
    if isinstance(root, dict):
        add(root.get("kind"), root)
    for field in ("method_as_data_refs",):
        for ref in _rows(execution, field):
            add(ref.get("kind"), ref)
    for field in ("application_frames", "instruction_refs"):
        for step in _rows(execution, field):
            method = step.get("method_ref")
            if isinstance(method, dict):
                add(method.get("kind"), method)
            for name in ("input_refs", "output_node_refs"):
                for ref in _rows(step, name):
                    add(ref.get("kind"), ref)


def capability_table(frame: dict) -> list[dict]:
    return [cap.as_dict() for cap in collect_capabilities(frame)]


def resolve_handle(frame: dict, object_id: str, kind: str | None = None,
                   version: str | None = None) -> Capability:
    if type(object_id) is not str or not object_id:
        raise CapabilityError("HANDLE_UNKNOWN")
    caps = [cap for cap in collect_capabilities(frame) if cap.object_id == object_id]
    if not caps:
        raise CapabilityError("HANDLE_UNKNOWN")
    if kind is not None:
        normalized = _kind(kind)
        caps = [cap for cap in caps if cap.kind == normalized]
        if not caps:
            raise CapabilityError("HANDLE_KIND_MISMATCH")
    if version is not None:
        caps = [cap for cap in caps if cap.version == version]
        if not caps:
            raise CapabilityError("HANDLE_VERSION_MISMATCH")
    if len(caps) != 1:
        raise CapabilityError("HANDLE_AMBIGUOUS")
    return caps[0]


def offered_ids(frame: dict) -> dict[str, set[str]]:
    offered = {kind: set() for kind in KINDS}
    for cap in collect_capabilities(frame):
        offered[cap.kind].add(cap.object_id)
    offered["edge"] = offered["link"]
    return offered
